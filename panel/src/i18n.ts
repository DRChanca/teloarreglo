export const languages = ["es", "en", "fr", "de"] as const;
export type Language = (typeof languages)[number];
export const languageNames: Record<Language, string> = { es: "Español", en: "English", fr: "Français", de: "Deutsch" };
export const messages: Record<Language, Messages> = { es, en, fr, de };

export function translate(language: Language, key: MessageKey, values: Record<string, string | number> = {}): string {
  return messages[language][key].replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? ""));
}

export function initialLanguage(): Language {
  try {
    const saved = localStorage.getItem("teloarreglo-panel-language");
    if (saved && (languages as readonly string[]).includes(saved)) return saved as Language;
  } catch { /* storage unavailable */ }
  const preferred = (typeof navigator !== "undefined" ? navigator.language : "es").slice(0, 2);
  return (languages as readonly string[]).includes(preferred) ? (preferred as Language) : "es";
}
